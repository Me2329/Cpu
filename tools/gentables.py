#!/usr/bin/env python3
"""gentables.py - fixed-point lookup tables for the raycaster (games/trig.inc).

Angles use 256 steps per full turn. Values are signed 8.8 fixed point
(256 = 1.0). The tables are emitted as assembler DW directives, the same
way a 16-bit DOS game would ship precomputed tables instead of an FPU.
"""
import math
import os


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, 'games', 'trig.inc')
    lines = ['; Generated by tools/gentables.py - do not edit.',
             '; 256-step angles, signed 8.8 fixed point.',
             'SECTION .data']
    sin = [round(math.sin(2 * math.pi * a / 256) * 256) for a in range(256)]
    cos = [round(math.cos(2 * math.pi * a / 256) * 256) for a in range(256)]
    for name, tab in (('sin_tab', sin), ('cos_tab', cos)):
        lines.append('%s:' % name)
        for i in range(0, 256, 16):
            lines.append('        DW ' + ', '.join(str(v) for v in tab[i:i + 16]))
    # camera-plane x coordinate for each of the 160 screen columns:
    # cameraX = 2*c/160 - 1, in 8.8 fixed point (-256 .. +253)
    lines.append('; column -> camera plane x (8.8)')
    lines.append('cam_tab:')
    cam = [round((2 * c / 160 - 1) * 256) for c in range(160)]
    for i in range(0, 160, 16):
        lines.append('        DW ' + ', '.join(str(v) for v in cam[i:i + 16]))
    lines.append('SECTION .code')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
